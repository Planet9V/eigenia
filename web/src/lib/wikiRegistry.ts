export function getAllWorkingGroups(lang: "en" | "nl" = "en"): WorkingGroupCategory[] {
  if (lang === "nl") {
    return WORKING_GROUPS.map(wg => ({
      ...wg,
      title: wg.titleNl || wg.title,
      subtitle: wg.subtitleNl || wg.subtitle,
      description: wg.descriptionNl || wg.description,
      badge: wg.badgeNl || wg.badge,
      documents: wg.documents.map(d => ({
        ...d,
        title: d.titleNl || d.title,
        subtitle: d.subtitleNl || d.subtitle,
        badge: d.badgeNl || d.badge,
        workingGroupName: d.workingGroupNameNl || d.workingGroupName
      }))
    }));
  }
  return WORKING_GROUPS;
}

export function getWorkingGroupById(id: string, lang: "en" | "nl" = "en"): WorkingGroupCategory | undefined {
  const wgs = getAllWorkingGroups(lang);
  return wgs.find((wg) => wg.id.toLowerCase() === id.toLowerCase() || (id.toLowerCase() === "wg-09" && wg.id.toLowerCase() === "wg-09-mpn"));
}

export function getAllWikiDocuments(lang: "en" | "nl" = "en"): WikiDocumentMeta[] {
  return getAllWorkingGroups(lang).flatMap((wg) => wg.documents);
}

/**
 * Documents marked for the homepage Featured Findings band.
 *
 * Reads metadata only. Never import ./wiki from a homepage component: it pulls
 * generatedReferencesContent.json, about 3.3 MB, into the client bundle. That is
 * why `hook` is a metadata field rather than an excerpt taken from the paper.
 */
export function getFeaturedDocuments(): WikiDocumentMeta[] {
  return getAllWikiDocuments()
    .filter((d) => d.featured === true)
    .sort((a, b) => (a.featuredRank ?? 999) - (b.featuredRank ?? 999));
}

/**
 * One document's metadata by its published slug.
 *
 * Used by the paper route for SEO: the subtitle becomes the meta description
 * and the publication date becomes datePublished in the ScholarlyArticle
 * schema. Both were previously absent, so every paper advertised the first 160
 * characters of its own body, truncated mid-sentence, and no date at all.
 *
 * Reads metadata only. It must stay in this module rather than ./wiki, which
 * pulls the generated content bundle.
 */
export function getWikiDocumentBySlug(slug: string): WikiDocumentMeta | undefined {
  return getAllWikiDocuments().find((d) => d.slug === slug);
}
