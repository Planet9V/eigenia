/**
 * Get the exact word count for a treatise by slug.
 * Returns a conservative fallback (2500 words) if the slug is unrecognized.
 */
export function getTreatiseWordCount(slug: string): number {
  return TREATISE_WORD_COUNTS[slug] ?? 2500;
}

/**
 * Calculates estimated reading time in whole minutes at standard technical reading speed (225 wpm).
 * Guaranteed to be at least 1 minute.
 */
export function getReadingMinutes(words: number): number {
  return Math.max(1, Math.round(words / 225));
}

/**
 * Formats reading time with locale awareness.
 */
export function formatReadingTime(words: number, locale: "en" | "nl" = "en"): string {
  const mins = getReadingMinutes(words);
  if (locale === "nl") {
    return `${mins} min leestijd`;
  }
  return `${mins} min read`;
}

